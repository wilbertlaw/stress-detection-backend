import os
import pickle
import torch
import nltk
import pandas as pd
import torch.nn as nn
import speech_recognition as sr
import streamlit as st
from torch.utils.data import Dataset
from nltk.tokenize import word_tokenize

# 設定 NLTK (使用快取避免重複下載)
@st.cache_resource
def download_nltk():
    nltk.download('punkt')
    nltk.download('punkt_tab')

download_nltk()

# --- 類別定義保持不變 ---
class TextDataset(Dataset):
    def __init__(self, csv_file):
        self.df = pd.read_csv(csv_file, encoding='latin1')
        self.texts = self.df['text'].values
        self.label = self.df['label'].values
        self.cache_file_path = 'token_cache.pkl'

        # 在 Streamlit 中直接執行，不顯示太多 print
        self.tokenize_text()
        self.vocab = self.create_vocab(self.tokens)
        self.prepared_text_data = [self.encode_tokens(token_list) for token_list in self.tokens]

    def tokenize_text(self):
        # 簡單化處理，若沒有 cache 就直接 tokenize
        if os.path.exists(self.cache_file_path):
            self.tokens = self.load_tokens()
        else:
            self.tokens = [word_tokenize(text.lower()) for text in self.texts]
            self.save_tokens(self.tokens)

    def create_vocab(self, tokens):
        vocab = {}
        for token_list in tokens:
            for token in token_list:
                if token not in vocab:
                    vocab[token] = len(vocab) + 1
        return vocab

    def encode_tokens(self, tokens):
        return [self.vocab.get(token, 0) for token in tokens]

    def save_tokens(self, tokens):
        try:
            with open(self.cache_file_path, 'wb') as f:
                pickle.dump(tokens, f)
        except:
            pass # 雲端環境權限問題可忽略

    def load_tokens(self):
        with open(self.cache_file_path, 'rb') as f:
            return pickle.load(f)

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        encoded_text = self.prepared_text_data[idx]
        label = self.label[idx]
        return torch.tensor(encoded_text), torch.tensor(label)

class GRUClassifier(nn.Module):
    def __init__(self, embedding_dim, hidden_dim, vocab_size, output_size, num_layers=1):
        super(GRUClassifier, self).__init__()
        self.embedding = nn.Embedding(vocab_size, embedding_dim)
        self.rnn = nn.GRU(embedding_dim, hidden_dim, num_layers, batch_first=True)
        self.fc = nn.Linear(hidden_dim, output_size)

    def forward(self, x):
        embedded = self.embedding(x)
        _, rnn_hidden = self.rnn(embedded)
        out = self.fc(rnn_hidden[-1])
        return out

# --- 初始化模型 (使用快取) ---
@st.cache_resource
def load_model_and_data():
    dataset_path = 'Stress.csv'
    if not os.path.exists(dataset_path):
        st.error("找不到 Stress.csv 檔案，請確認已上傳。")
        return None, None, None

    dataset = TextDataset(dataset_path)
    vocab_size = len(dataset.vocab) + 1
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

    model = GRUClassifier(200, 128, vocab_size, 2, 6).to(device)
    model.eval() # 設定為評估模式
    return model, dataset, device

# --- 預測函數 ---
def predict_text(text_input, model, dataset, device):
    if not text_input.strip():
        return "請輸入文字", ""

    tokens = word_tokenize(text_input.lower())
    encoded = torch.tensor([dataset.vocab.get(t, 0) for t in tokens]).unsqueeze(0).to(device)

    with torch.no_grad():
        outputs = model(encoded)
        probs = torch.softmax(outputs, dim=1)
        conf, pred = torch.max(probs, 1)

    label = 'Stress Detected (有壓力)' if pred.item() == 1 else 'No Stress Detected (無壓力)'
    confidence = f'{conf.item()*100:.2f}%'
    return label, confidence

# --- Streamlit 主程式 ---
st.title("Stress Detection App")
st.write("輸入文字或上傳音檔來檢測壓力指數。")

model, dataset, device = load_model_and_data()

if model:
    tab1, tab2 = st.tabs(["📝 文字輸入", "🎤 音訊上傳"])

    with tab1:
        user_text = st.text_area("在此輸入英文句子:", height=150)
        if st.button("分析文字"):
            res, conf = predict_text(user_text, model, dataset, device)
            st.success(f"結果: {res}")
            st.info(f"信心水準: {conf}")

    with tab2:
        uploaded_file = st.file_uploader("上傳音訊檔案 (WAV)", type=["wav"])
        if uploaded_file is not None:
            st.audio(uploaded_file, format='audio/wav')
            if st.button("分析音訊"):
                r = sr.Recognizer()
                try:
                    # SpeechRecognition 支援讀取 file-like object
                    with sr.AudioFile(uploaded_file) as source:
                        audio_data = r.record(source)
                        text = r.recognize_google(audio_data)
                        st.write(f"辨識到的文字: **{text}**")

                        # 進行預測
                        res, conf = predict_text(text, model, dataset, device)
                        st.success(f"結果: {res}")
                        st.info(f"信心水準: {conf}")
                except Exception as e:
                    st.error(f"音訊處理錯誤: {e}")
def predict_with_gru(text_input, dataset, model, device):
  if not text_input.strip(): return '無有效輸入', '0%'
  tokens = word_tokenize(text_input.lower())
  encoded = torch.tensor([dataset.vocab.get(t, 0) for t in tokens]).unsqueeze(0).to(device)
  model.eval()
  with torch.no_grad():
    outputs = model(encoded)
    probs = torch.softmax(outputs, dim=1)
    conf, pred = torch.max(probs, 1)
  res = '偵測到壓力狀態 (Stress Detected)' if pred.item() == 1 else '未偵測到壓力 (No Stress Detected)'
  return res, f'{conf.item()*100:.2f}%'

def predict_stress_audio(audio_input, dataset, model, device):
  r = sr.Recognizer()
  with sr.AudioFile(audio_input) as source:
    audio = r.record(source)
  text = r.recognize_google(audio)

  # 在畫面上額外顯示辨識出的文字內容
  st.info(f"🎙️ 語音辨識文本：\"{text}\"")
  return predict_with_gru(text, dataset, model, device)

